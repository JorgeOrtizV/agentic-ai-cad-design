"""
Parse a natural language CAD specification into a structured PartSpec.

1. Ask the LLM for JSON constrained to the PartSpec schema
2. Validate the JSON against the schema (pydantic)
3. Run deterministic checks: positive dimensions and numeric grounding against the source text
4. If any check fails, feed the errors back to the LLM and retry
"""

import argparse
import json
import logging
import re
from collections.abc import Callable
from pathlib import Path

from pydantic import ValidationError

from llm_client import DEFAULT_MODEL, ask_llm
from schemas import PartSpec

logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PROMPT_PATH = PROJECT_ROOT / "prompts" / "parse_specification.md"
OUTPUT_DIR = PROJECT_ROOT / "outputs"

MAX_PARSE_ATTEMPTS = 3

NUMBER_WORDS = {
    "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6,
    "seven": 7, "eight": 8, "nine": 9, "ten": 10, "eleven": 11, "twelve": 12,
    "single": 1, "pair": 2, "double": 2, "twin": 2,
}

# Match digits either integer or float using different , or . conventions
NUMBER_PATTERN = re.compile(r"\d+(?:[.,]\d+)?")
# Find back ticking generated by LLM
CODE_FENCE_PATTERN = re.compile(r"^```(?:json)?\s*|\s*```$")

LLMCallable = Callable[..., str | None]

# TODO: create an excepion file and import exceptions
class SpecParseError(Exception):
    """Raised when the LLM output cannot be turned into a valid PartSpec."""


def extract_numbers(text: str) -> set[float]:
    """Return every number in the text, including written counts like 'two'."""
    numbers = {float(match.replace(",", ".")) for match in NUMBER_PATTERN.findall(text)}
    words = re.findall(r"[a-z]+", text.lower())
    numbers.update(float(NUMBER_WORDS[word]) for word in words if word in NUMBER_WORDS)
    return numbers


def check_spec(spec: PartSpec, source_text: str) -> tuple[list[str], list[str]]:
    """
    Deterministic checks on a parsed spec.
    Returns (errors, warnings): errors trigger a retry, warnings are only reported.
    """
    errors: list[str] = []
    warnings: list[str] = []

    for name, value in spec.parameters.items():
        if value <= 0:
            errors.append(f"Parameter '{name}' must be positive, got {value}")
    for feature in spec.features:
        for name, value in feature.parameters.items():
            if value <= 0:
                errors.append(f"Feature '{feature.type}' parameter '{name}' must be positive, got {value}")

    # Grounding: every dimension must come from the text or be justified in an assumption
    source_numbers = extract_numbers(source_text)
    assumption_numbers = extract_numbers(" ".join(spec.assumptions))
    grounded = source_numbers | assumption_numbers

    dimensions = [(f"parameter '{name}'", value) for name, value in spec.parameters.items()]
    dimensions += [(f"feature '{f.type}' parameter '{name}'", value) for f in spec.features for name, value in f.parameters.items()]
    for label, value in dimensions:
        if value not in grounded:
            errors.append(
                f"The {label} = {value:g} does not appear in the specification. "
                "Remove it and list it in missing_parameters, or justify it in assumptions."
            )

    # Derived counts (e.g. 'two holes in each leg' -> 4) are legitimate, so only warn
    warnings.extend(
        f"Feature '{feature.type}' count {feature.count} is derived, not stated in the specification"
        for feature in spec.features
        if feature.count > 1 and feature.count not in grounded
    )

    # Coverage: every number in the text should be captured somewhere
    location_numbers = extract_numbers(" ".join(feature.location or "" for feature in spec.features))
    captured = {value for _, value in dimensions} | {float(f.count) for f in spec.features} | assumption_numbers | location_numbers
    for value in sorted(source_numbers - captured):
        if value == 1:  # 'one', 'single' are often articles rather than quantities
            continue
        errors.append(f"The value {value:g} from the specification is not captured in the output")

    return errors, warnings


def _load_prompt(specification: str) -> str:
    template = PROMPT_PATH.read_text(encoding="utf-8")
    return template.replace("{specification}", specification)


def _to_part_spec(raw: str | None) -> PartSpec:
    if not raw:
        raise SpecParseError("LLM returned an empty response")
    cleaned = CODE_FENCE_PATTERN.sub("", raw.strip())
    try:
        # Check if valid json format according our Pydantic definition
        return PartSpec.model_validate_json(cleaned)
    except ValidationError as exc:
        raise SpecParseError(f"Output does not match the schema:\n{exc}") from exc


def parse_specification(
    natural_language_spec: str,
    model: str = DEFAULT_MODEL,
    max_attempts: int = MAX_PARSE_ATTEMPTS,
    llm: LLMCallable = ask_llm,
) -> PartSpec:
    """
    Turn a natural language specification into a PartSpec.

    Raises SpecParseError if no schema-valid output is produced within max_attempts.
    If the output is schema-valid but still fails the checks after the last attempt,
    the best spec is returned with the remaining problems in `warnings`.
    """
    natural_language_spec = natural_language_spec.strip()
    if not natural_language_spec:
        raise ValueError("Specification is empty")

    # Define prompt asking the model to transform given NL specification to spec
    messages = [{"role": "user", "content": _load_prompt(natural_language_spec)}]
    schema = PartSpec.model_json_schema()

    # Save best generated spec: [spec, errors, warnings]
    best: tuple[PartSpec, list[str], list[str]] | None = None
    last_error = ""

    for attempt in range(1, max_attempts + 1):
        raw = llm(model=model, messages=messages, schema=schema, temperature=0)
        messages.append({"role": "assistant", "content": raw or ""})

        try:
            spec = _to_part_spec(raw)
        except SpecParseError as exc:
            last_error = str(exc)
            logger.info("Parse attempt %d: invalid output: %s", attempt, last_error)
            messages.append({"role": "user", "content": f"{last_error}\nReturn the corrected JSON only."})
            continue

        errors, warnings = check_spec(spec, natural_language_spec)
        if best is None or len(errors) <= len(best[1]):
            best = (spec, errors, warnings)
        # Early stop if no errors.
        if not errors:
            logger.info("Parse attempt %d: spec accepted", attempt)
            break

        logger.info("Parse attempt %d: %d check errors", attempt, len(errors))
        feedback = "\n".join(f"- {error}" for error in errors)
        messages.append(
            {
                "role": "user",
                "content": f"Your output has these problems:\n{feedback}\nFix them and return the corrected JSON only.",
            }
        )

    if best is None:
        raise SpecParseError(f"No valid specification after {max_attempts} attempts. Last error: {last_error}")

    spec, errors, warnings = best
    return spec.model_copy(update={"warnings": errors + warnings})


def save_spec(spec: PartSpec, name: str, output_dir: Path = OUTPUT_DIR) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / f"{name}.spec.json"
    path.write_text(spec.model_dump_json(indent=2), encoding="utf-8")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description="Parse a natural language CAD specification")
    parser.add_argument("spec_file", type=Path, help="Text file with the specification, e.g. specs/bracket.txt")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO if args.verbose else logging.WARNING)

    spec = parse_specification(args.spec_file.read_text(encoding="utf-8"), model=args.model)
    path = save_spec(spec, args.spec_file.stem)
    print(json.dumps(spec.model_dump(), indent=2))
    print(f"\nSaved to {path}")


if __name__ == "__main__":
    main()
